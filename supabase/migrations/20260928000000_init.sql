-- Portfolio content schema for Supabase.
-- Replaces the Notion databases (stack, writing, AMA) and Cloudflare R2 image storage.
--
-- Access model:
--   * Public (anon) can read published content and submit AMA questions.
--   * Everything else (creating and editing content) goes through
--     the service role key on the server, which bypasses RLS.

-- ---------------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------------

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- Stack: apps and tools I use  (was NOTION_STACK_DATABASE_ID)
-- ---------------------------------------------------------------------------

create table public.stack_items (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  slug        text not null unique,
  description text,
  url         text,
  image       text,            -- screenshot / cover image URL
  icon        text,            -- app icon URL (was generated by the process-stack-icon webhook)
  platforms   text[] not null default '{}'
              check (platforms <@ array['macOS', 'iOS', 'Windows', 'Web', 'Physical']),
  status      text not null default 'active' check (status in ('active', 'inactive')),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index stack_items_status_name_idx on public.stack_items (status, name);

create trigger stack_items_set_updated_at
  before update on public.stack_items
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- Writing: blog posts  (was NOTION_WRITING_DATABASE_ID)
-- A post is public once published_at is set and in the past.
-- ---------------------------------------------------------------------------

create table public.writing_posts (
  id            uuid primary key default gen_random_uuid(),
  title         text not null,
  slug          text not null unique,
  excerpt       text,
  feature_image text,
  content       text not null default '',   -- Markdown body (replaces Notion page blocks)
  published_at  timestamptz,                 -- null = draft
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create index writing_posts_published_at_idx
  on public.writing_posts (published_at desc)
  where published_at is not null;

create trigger writing_posts_set_updated_at
  before update on public.writing_posts
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- AMA: questions from visitors and my answers  (was NOTION_AMA_DATABASE_ID)
-- ---------------------------------------------------------------------------

create table public.ama_questions (
  id           uuid primary key default gen_random_uuid(),
  title        text not null check (char_length(title) between 1 and 280),
  description  text check (char_length(description) <= 2000),
  answer       text,                        -- Markdown answer (replaces Notion page blocks)
  status       text not null default 'unanswered'
               check (status in ('unanswered', 'answered', 'wont_answer')),
  answered_at  timestamptz,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  constraint ama_answered_has_answer
    check (status <> 'answered' or (answer is not null and answered_at is not null))
);

create index ama_questions_answered_idx
  on public.ama_questions (answered_at desc)
  where status = 'answered';

create trigger ama_questions_set_updated_at
  before update on public.ama_questions
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- Row level security
-- ---------------------------------------------------------------------------

alter table public.stack_items       enable row level security;
alter table public.writing_posts     enable row level security;
alter table public.ama_questions     enable row level security;

create policy "Active stack items are public"
  on public.stack_items for select
  to anon, authenticated
  using (status = 'active');

create policy "Published posts are public"
  on public.writing_posts for select
  to anon, authenticated
  using (published_at is not null and published_at <= now());

create policy "Answered AMA questions are public"
  on public.ama_questions for select
  to anon, authenticated
  using (status = 'answered');

-- Visitors can ask a question, but can't answer it or set its status.
create policy "Anyone can ask an AMA question"
  on public.ama_questions for insert
  to anon, authenticated
  with check (status = 'unanswered' and answer is null and answered_at is null);

-- ---------------------------------------------------------------------------
-- Image storage (replaces Cloudflare R2)
-- Public bucket for post images, feature images and icons. Anyone can view files;
-- uploads, replacements and deletes go through the service role key on the server.
-- Public URL: <SUPABASE_URL>/storage/v1/object/public/images/<path>
-- ---------------------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'images',
  'images',
  true,
  10485760, -- 10 MB
  array['image/png', 'image/jpeg', 'image/webp', 'image/gif', 'image/avif', 'image/svg+xml']
)
on conflict (id) do nothing;

create policy "Images are public"
  on storage.objects for select
  to anon, authenticated
  using (bucket_id = 'images');
